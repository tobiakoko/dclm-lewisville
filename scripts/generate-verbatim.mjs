// Regenerates lib/content/verbatim.generated.ts (the VERBATIM blocks) and
// lib/content/approved.generated.ts (approved copy under the headings in APPROVED_SECTIONS)
// from docs/build/SITE-CONTENT.md, so the church's words are never retyped by hand.
// Usage: node scripts/generate-verbatim.mjs
// __tests__/content/verbatim.test.ts fails if the two ever drift apart.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import source from './verbatim-source.cjs'

const { APPROVED_SECTIONS, VERBATIM_KEYS, extractSection, extractVerbatimBlocks, toInline } = source

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const markdown = readFileSync(path.join(root, 'docs/build/SITE-CONTENT.md'), 'utf8')

const blocks = extractVerbatimBlocks(markdown)
const out = {}
for (const [label, paragraphs] of Object.entries(blocks)) {
  const key = VERBATIM_KEYS[label]
  if (!key) throw new Error(`No export name for VERBATIM block "${label}"`)
  out[key] = paragraphs.map(toInline)
}

const approved = {}
for (const [key, heading] of Object.entries(APPROVED_SECTIONS)) {
  approved[key] = extractSection(markdown, heading).map(toInline)
}

function render(entries) {
  return Object.entries(entries)
    .map(([key, value]) => `export const ${key}: Paragraph[] = ${JSON.stringify(value, null, 2)}\n`)
    .join('\n')
}

const header = `// GENERATED by scripts/generate-verbatim.mjs from docs/build/SITE-CONTENT.md. Do not edit;\n` +
  `// change SITE-CONTENT.md and run \`node scripts/generate-verbatim.mjs\`.\n`

writeFileSync(
  path.join(root, 'lib/content/verbatim.generated.ts'),
  header +
    `// VERBATIM: supplied by the church; published word for word (CLAUDE.md rule 2).\n` +
    `import type { Paragraph } from './inline'\n\n` +
    render(out)
)
writeFileSync(
  path.join(root, 'lib/content/approved.generated.ts'),
  header + `// Approved copy: layout may change, wording may not.\n` + `import type { Paragraph } from './inline'\n\n` + render(approved)
)
console.log(`Wrote verbatim: ${Object.keys(out).join(', ')}; approved: ${Object.keys(approved).join(', ')}`)
